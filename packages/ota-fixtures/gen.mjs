// Plural data for the OTA SDKs (Swift, Kotlin). Input: CLDR cldr-core/supplemental/plurals.json
// (https://github.com/unicode-org/cldr-json). Output: rules.json + the generated Swift/Kotlin sources.
// plural-cases.json (the expected categories) comes from glot's validator (glot_core::plural, ICU4X):
// each SDK's tests check its evaluator against it.
// Usage: node gen.mjs plurals.json && cargo run --release --manifest-path fixgen/Cargo.toml -- plurals.json > plural-cases.json
import { readFileSync, writeFileSync } from "node:fs";

const cldr = JSON.parse(readFileSync(process.argv[2], "utf8"));
const rules = {};
for (const [loc, r] of Object.entries(cldr.supplemental["plurals-type-cardinal"])) {
  const out = {};
  for (const [k, v] of Object.entries(r)) {
    const cat = k.replace("pluralRule-count-", "");
    const cond = v.split("@")[0].trim();
    if (cat !== "other" && cond) out[cat] = cond;
  }
  rules[loc] = out;
}
const json = JSON.stringify(rules);
writeFileSync(new URL("rules.json", import.meta.url), json + "\n");
const head = "// Generated by packages/ota-fixtures/gen.mjs from CLDR plurals.json. Do not edit.\n";
writeFileSync(
  new URL("../ota-ios/Sources/Glot/PluralData.swift", import.meta.url),
  `${head}let pluralData = #"${json}"#\n`,
);
writeFileSync(
  new URL("../ota-android/glot/src/main/kotlin/dev/glot/ota/PluralData.kt", import.meta.url),
  `${head}package dev.glot.ota\n\ninternal const val PLURAL_DATA = """${json}"""\n`,
);
console.log(`${Object.keys(rules).length} locales, ${json.length} bytes`);
