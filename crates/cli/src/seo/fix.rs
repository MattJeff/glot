//! `glot seo fix` (Next.js App Router, after `glot i18nize`): canonical + hreflang alternates for
//! every page from the root layout's `generateMetadata`, multi-locale `app/sitemap.ts`, `app/robots.ts`.
//! Same contract as the i18nize setup: span edits, idempotent, every change visible in `--dry-run`.
use std::path::Path;

use oxc_allocator::Allocator;
use oxc_ast::ast::*;
use oxc_span::GetSpan;

use crate::setup::refactor::{apply_edits, line_indent, parse};
use crate::setup::{Framework, Project, SetupPlan, add_import, exists_any, rel_import};

const ALT: &str = "alternates: await seoAlternates(),";

fn seo_ts() -> String {
    r#"// Generated by `glot seo fix`: canonical + hreflang alternates for the current request.
import type { Metadata } from "next";
import { headers } from "next/headers";
import { routing } from "./routing";

/** Public origin; set SITE_URL (https://example.com) in production, else the request host is used. */
export const SITE_URL = (process.env.SITE_URL ?? "").replace(/\/$/, "");

/** URL of `path` in `locale`: the default locale has no prefix, the others live under /fr/... */
export function localeUrl(origin: string, locale: string, path: string) {
  const p = locale === routing.defaultLocale ? path : `/${locale}${path === "/" ? "" : path}`;
  return origin + p;
}

/** `alternates` for generateMetadata: self canonical + one hreflang per locale + x-default. */
export async function seoAlternates(): Promise<Metadata["alternates"]> {
  const h = await headers();
  const locale = h.get("x-glot-locale") ?? routing.defaultLocale;
  const path = h.get("x-glot-pathname") ?? "/";
  const host = h.get("x-forwarded-host") ?? h.get("host") ?? "localhost:3000";
  const proto = h.get("x-forwarded-proto") ?? (/^(localhost|127\.)/.test(host) ? "http" : "https");
  const origin = SITE_URL || `${proto}://${host}`;
  const languages: Record<string, string> = {};
  for (const l of routing.locales) languages[l] = localeUrl(origin, l, path);
  languages["x-default"] = localeUrl(origin, routing.defaultLocale, path);
  return { canonical: localeUrl(origin, locale, path), languages };
}
"#
    .into()
}

fn sitemap_ts(i18n: &str, routes: &[String]) -> String {
    format!(
        r#"// Generated by `glot seo fix`: every page in every locale, with hreflang alternates.
// Add dynamic pages (from your data) to ROUTES. Absolute URLs come from SITE_URL.
import type {{ MetadataRoute }} from "next";
import {{ routing }} from "{i18n}/routing";
import {{ SITE_URL, localeUrl }} from "{i18n}/seo";

const ROUTES = {};

export default function sitemap(): MetadataRoute.Sitemap {{
  const origin = SITE_URL || "http://localhost:3000";
  return ROUTES.flatMap((path) => {{
    const languages = Object.fromEntries(routing.locales.map((l) => [l, localeUrl(origin, l, path)]));
    return routing.locales.map((l) => ({{ url: localeUrl(origin, l, path), alternates: {{ languages }} }}));
  }});
}}
"#,
        serde_json::to_string(routes).unwrap()
    )
}

fn robots_ts(i18n: &str) -> String {
    format!(
        r#"// Generated by `glot seo fix`.
import type {{ MetadataRoute }} from "next";
import {{ SITE_URL }} from "{i18n}/seo";

export default function robots(): MetadataRoute.Robots {{
  return {{ rules: {{ userAgent: "*", allow: "/" }}, sitemap: `${{SITE_URL || "http://localhost:3000"}}/sitemap.xml` }};
}}
"#
    )
}

/// Static routes of `app/` (route groups stripped); dynamic ones (`[id]`) are returned apart.
pub fn routes(app: &Path) -> (Vec<String>, Vec<String>) {
    fn walk(dir: &Path, segs: &mut Vec<String>, out: &mut (Vec<String>, Vec<String>)) {
        let Ok(rd) = std::fs::read_dir(dir) else {
            return;
        };
        let mut entries: Vec<_> = rd.flatten().collect();
        entries.sort_by_key(|e| e.file_name());
        for e in entries {
            let name = e.file_name().to_string_lossy().to_string();
            if e.path().is_dir() {
                if name.starts_with(['_', '@', '.']) || name == "api" || name == "node_modules" {
                    continue;
                }
                segs.push(name);
                walk(&e.path(), segs, out);
                segs.pop();
            } else if ["page.tsx", "page.jsx", "page.ts", "page.js", "page.mdx"]
                .contains(&name.as_str())
            {
                let parts: Vec<&str> = segs
                    .iter()
                    .map(String::as_str)
                    .filter(|s| !(s.starts_with('(') && s.ends_with(')')))
                    .collect();
                let route = format!("/{}", parts.join("/"));
                if parts.iter().any(|s| s.starts_with('[')) {
                    out.1.push(route)
                } else {
                    out.0.push(route)
                }
            }
        }
    }
    let mut out = (vec![], vec![]);
    walk(app, &mut vec![], &mut out);
    out.0.sort();
    out
}

/// Insert `alternates` into `generateMetadata`'s returned object, or turn `export const metadata = {..}`
/// into an async `generateMetadata`. Ok(None) = already done.
pub fn layout_edit(path: &str, src: &str) -> Result<Option<String>, String> {
    if src.contains("seoAlternates") {
        return Ok(None);
    }
    let alloc = Allocator::default();
    let program = parse(&alloc, path, src).ok_or("does not parse")?;
    let insert = |o: &ObjectExpression| -> Result<(u32, u32, String), String> {
        if o.properties.iter().any(|p| matches!(p, ObjectPropertyKind::ObjectProperty(p) if p.key.static_name().as_deref() == Some("alternates"))) {
            return Err("metadata already sets `alternates`: left as is".into());
        }
        Ok(match o.properties.first() {
            Some(p) => {
                let s = p.span().start;
                let sep = if src[o.span.start as usize..s as usize].contains('\n') {
                    format!("\n{}", line_indent(src, s))
                } else {
                    " ".into()
                };
                (s, s, format!("{ALT}{sep}"))
            }
            None => (o.span.start + 1, o.span.start + 1, format!(" {ALT} ")),
        })
    };
    for st in &program.body {
        let Statement::ExportDeclaration(ex) = st else {
            continue;
        };
        match &ex.declaration {
            Declaration::FunctionDeclaration(f)
                if f.id.as_ref().is_some_and(|i| i.name == "generateMetadata") =>
            {
                if !f.r#async {
                    return Err("generateMetadata is not async: add `alternates: await seoAlternates()` by hand".into());
                }
                let obj = f.body.as_ref().and_then(|b| {
                    b.statements.iter().rev().find_map(|s| match s {
                        Statement::ReturnStatement(r) => {
                            match r.argument.as_ref()?.get_inner_expression() {
                                Expression::ObjectExpression(o) => Some(o),
                                _ => None,
                            }
                        }
                        _ => None,
                    })
                });
                let o = obj.ok_or("generateMetadata does not return an object literal: add `alternates: await seoAlternates()` by hand")?;
                return Ok(apply_edits(src, vec![insert(o)?]));
            }
            Declaration::VariableDeclaration(v) => {
                let [d] = v.declarations.as_slice() else {
                    continue;
                };
                let (BindingPattern::BindingIdentifier(id), Some(init)) = (&d.id, &d.init) else {
                    continue;
                };
                let Expression::ObjectExpression(o) = init.get_inner_expression() else {
                    continue;
                };
                if id.name != "metadata" {
                    continue;
                }
                let ret = d
                    .type_annotation
                    .as_ref()
                    .map(|a| {
                        let s = a.type_annotation.span();
                        format!(": Promise<{}>", &src[s.start as usize..s.end as usize])
                    })
                    .unwrap_or_default();
                let (os, oe) = (o.span.start, o.span.end);
                return Ok(apply_edits(
                    src,
                    vec![
                        (
                            v.span.start,
                            os,
                            format!("async function generateMetadata(){ret} {{\n  return "),
                        ),
                        insert(o)?,
                        (oe, v.span.end, ";\n}".into()),
                    ],
                ));
            }
            _ => {}
        }
    }
    Err("no exported `generateMetadata` / `metadata`: add `alternates: await seoAlternates()` to your metadata".into())
}

pub fn plan(root: &Path, p: &Project) -> Result<SetupPlan, String> {
    if p.framework != Framework::NextApp {
        return Err(format!(
            "`glot seo fix` supports the Next.js App Router ({} detected); `glot seo audit` works on any site",
            p.framework.label()
        ));
    }
    let b = p.base;
    let i18n = format!("{b}i18n");
    let proxy = format!("{i18n}/proxy.ts");
    if !root.join(&proxy).is_file() || !root.join(format!("{i18n}/routing.ts")).is_file() {
        return Err(format!(
            "{proxy} not found: run `glot i18nize` first (it wires the locale routing)"
        ));
    }
    let mut plan = SetupPlan::default();
    // The proxy knows the unprefixed path: pass it to the metadata like the locale.
    plan.edit(root, &proxy, |src| {
        if src.contains("x-glot-pathname") {
            return Ok(None);
        }
        let anchor = "headers.set(\"x-glot-locale\", locale);";
        let at = src.find(anchor).ok_or(
            "no `x-glot-locale` header: set `x-glot-pathname` (path without locale prefix) by hand",
        )?;
        let indent = line_indent(src, at as u32);
        let end = at + anchor.len();
        Ok(apply_edits(
            src,
            vec![(
                end as u32,
                end as u32,
                format!("\n{indent}headers.set(\"x-glot-pathname\", rest);"),
            )],
        ))
    });
    plan.create(root, &format!("{i18n}/seo.ts"), seo_ts());
    let app = format!("{b}app");
    if let Some(layout) = exists_any(
        root,
        b,
        &[
            "app/layout.tsx",
            "app/layout.jsx",
            "app/layout.ts",
            "app/layout.js",
        ],
    ) {
        let import = format!(
            "import {{ seoAlternates }} from \"{}\";",
            rel_import(&app, &format!("{i18n}/seo"))
        );
        plan.edit(root, &layout.clone(), |src| {
            let Some(new) = layout_edit(&layout, src)? else {
                return Ok(None);
            };
            Ok(add_import(&layout, &new, &import))
        });
    }
    let (stat, dynamic) = routes(&root.join(&app));
    let rel = rel_import(&app, &i18n);
    // Our own files are re-planned (silent when unchanged); hand-written ones are left alone.
    let theirs = |names: &[&str], public: &str| {
        exists_any(root, b, names).is_some() || root.join(public).exists()
    };
    if theirs(&["app/sitemap.js", "app/sitemap.xml"], "public/sitemap.xml") {
        plan.notes.push(
            "sitemap exists: list every locale URL with hreflang alternates (see `glot seo audit`)"
                .into(),
        );
    } else {
        plan.create(root, &format!("{app}/sitemap.ts"), sitemap_ts(&rel, &stat));
        if !dynamic.is_empty() {
            plan.notes.push(format!(
                "{app}/sitemap.ts: add the dynamic pages ({}) to ROUTES",
                dynamic.join(", ")
            ));
        }
    }
    if !theirs(&["app/robots.js", "app/robots.txt"], "public/robots.txt") {
        plan.create(root, &format!("{app}/robots.ts"), robots_ts(&rel));
    }
    plan.notes.push("set SITE_URL (https://your-domain) at build and run time for absolute canonical/sitemap URLs".into());
    Ok(plan)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn layout_metadata_edits() {
        let gm = "import type { Metadata } from \"next\";\n\nexport async function generateMetadata(): Promise<Metadata> {\n  const t = await getTranslations(\"home\");\n  return {\n    title: t(\"title\"),\n  };\n}\n";
        let out = layout_edit("app/layout.tsx", gm).unwrap().unwrap();
        assert!(
            out.contains(
                "  return {\n    alternates: await seoAlternates(),\n    title: t(\"title\"),"
            ),
            "{out}"
        );
        assert_eq!(layout_edit("app/layout.tsx", &out).unwrap(), None);

        let c = "export const metadata: Metadata = { title: \"Acme\" };\n";
        let out = layout_edit("app/layout.tsx", c).unwrap().unwrap();
        assert_eq!(
            out,
            "export async function generateMetadata(): Promise<Metadata> {\n  return { alternates: await seoAlternates(), title: \"Acme\" };\n}\n"
        );
        assert!(layout_edit("a.tsx", "export const metadata = { alternates: {} };").is_err());
    }

    #[test]
    fn plan_is_idempotent() {
        let d = tempfile::tempdir().unwrap();
        let r = d.path();
        let w = |p: &str, s: &str| {
            std::fs::create_dir_all(r.join(p).parent().unwrap()).unwrap();
            std::fs::write(r.join(p), s).unwrap();
        };
        w(
            "package.json",
            r#"{"dependencies":{"next":"16.0.0","next-intl":"4"}}"#,
        );
        w(
            "app/layout.tsx",
            "export async function generateMetadata() {\n  return { title: \"A\" };\n}\nexport default function L({ children }) { return <html><body>{children}</body></html>; }\n",
        );
        w(
            "app/page.tsx",
            "export default function P() { return null; }\n",
        );
        w("app/(marketing)/pricing/page.tsx", "x");
        w("app/invoices/[id]/page.tsx", "x");
        w("i18n/routing.ts", "");
        w(
            "i18n/proxy.ts",
            "    headers.set(\"x-glot-locale\", locale);\n",
        );
        let p = crate::setup::detect(r).unwrap();
        let plan = plan(r, &p).unwrap();
        let paths: Vec<&str> = plan.changes.iter().map(|c| c.path.as_str()).collect();
        assert_eq!(
            paths,
            [
                "i18n/proxy.ts",
                "i18n/seo.ts",
                "app/layout.tsx",
                "app/sitemap.ts",
                "app/robots.ts"
            ]
        );
        let sitemap = &plan.changes[3].new;
        assert!(
            sitemap.contains(r#"const ROUTES = ["/","/pricing"];"#)
                && sitemap.contains("from \"../i18n/seo\""),
            "{sitemap}"
        );
        assert!(
            plan.changes[2]
                .new
                .starts_with("import { seoAlternates } from \"../i18n/seo\";\n")
        );
        crate::setup::write(r, &plan).unwrap();
        let again = super::plan(r, &p).unwrap();
        assert!(again.changes.is_empty());
    }
}
