const MATCHER: &str = r#"["/((?!api|_next|_vercel|.*\\..*).*)"]"#;

fn locales_list(o: &Opts) -> String {
    serde_json::to_string(&o.locales).unwrap()
}

/// Template-literal import path of a catalog from `dir` (`../locales/${locale}.json`).
fn catalog_tpl(dir: &str, o: &Opts) -> String {
    rel_import(dir, &o.catalog).replace("{locale}", "${locale}")
}

fn routing_ts(o: &Opts) -> String {
    let mode = match o.routing {
        Routing::Prefix => "prefix",
        Routing::Cookie => "cookie",
    };
    format!(
        r#"// Generated by `glot i18nize`. Locales mirror glot.toml (source locale first).
export const routing = {{
  locales: {} as string[],
  defaultLocale: "{}",
  // "cookie": /fr/... selects the locale and remembers it (NEXT_LOCALE cookie); unprefixed URLs keep it.
  // "prefix": non-default locales always live under /fr/... (as-needed: the default locale has no prefix).
  localePrefix: "{mode}" as "cookie" | "prefix",
}};
"#,
        locales_list(o),
        o.locales[0]
    )
}

fn request_ts(dir: &str, o: &Opts) -> String {
    format!(
        r#"import {{ getRequestConfig }} from "next-intl/server";
import {{ headers }} from "next/headers";
import {{ routing }} from "./routing";

type Messages = Record<string, unknown>;

async function load(locale: string): Promise<Messages> {{
  try {{
    return (await import(`{}`)).default;
  }} catch {{
    return {{}};
  }}
}}

// Keys not translated yet fall back to the source locale.
function merge(base: Messages, over: Messages): Messages {{
  const out: Messages = {{ ...base }};
  for (const [k, v] of Object.entries(over)) {{
    const b = out[k];
    out[k] = b && v && typeof b === "object" && typeof v === "object" ? merge(b as Messages, v as Messages) : v;
  }}
  return out;
}}

export default getRequestConfig(async () => {{
  // Set by the proxy from the URL prefix or the NEXT_LOCALE cookie (i18n/proxy.ts).
  const requested = (await headers()).get("x-glot-locale");
  const locale = routing.locales.find((l) => l === requested) ?? routing.defaultLocale;
  const source = await load(routing.defaultLocale);
  return {{ locale, messages: locale === routing.defaultLocale ? source : merge(source, await load(locale)) }};
}});
"#,
        catalog_tpl(dir, o)
    )
}

const PROXY_TS: &str = r#"import { NextResponse, type NextRequest } from "next/server";
import { routing } from "./routing";

const COOKIE = "NEXT_LOCALE";

/** Locale from the URL prefix (`/fr/...`, rewritten to `/...`) or the cookie, passed to i18n/request.ts. */
export function i18nProxy(req: NextRequest) {
  const { locales, defaultLocale, localePrefix } = routing;
  const path = req.nextUrl.pathname;
  const first = path.split("/")[1];
  const prefixed = locales.includes(first);
  const saved = req.cookies.get(COOKIE)?.value;
  const locale = prefixed ? first : saved && locales.includes(saved) ? saved : defaultLocale;
  const rest = (prefixed ? path.slice(first.length + 1) : path) || "/";
  const url = req.nextUrl.clone();
  let res: NextResponse;
  if (localePrefix === "prefix" && (prefixed ? locale === defaultLocale : locale !== defaultLocale)) {
    url.pathname = locale === defaultLocale ? rest : `/${locale}${rest === "/" ? "" : rest}`;
    res = NextResponse.redirect(url);
  } else {
    const headers = new Headers(req.headers);
    headers.set("x-glot-locale", locale);
    url.pathname = rest;
    res = prefixed ? NextResponse.rewrite(url, { request: { headers } }) : NextResponse.next({ request: { headers } });
  }
  if (prefixed && saved !== locale) {
    res.cookies.set(COOKIE, locale, { path: "/", maxAge: 60 * 60 * 24 * 365, sameSite: "lax" });
  }
  return res;
}
"#;

fn root_proxy(name: &str) -> String {
    format!(
        r#"import type {{ NextRequest }} from "next/server";
import {{ i18nProxy }} from "./i18n/proxy";

export default function {name}(req: NextRequest) {{
  return i18nProxy(req);
}}

export const config = {{ matcher: {MATCHER} }};
"#
    )
}

fn app_switcher(dir: &str, base: &str) -> String {
    format!(
        r#""use client";

import {{ useLocale, useTranslations }} from "next-intl";
import {{ routing }} from "{}";

/** Language picker generated by `glot i18nize --switcher`: drop it in a header or menu. */
export function LocaleSwitcher() {{
  const t = useTranslations("locale_switcher");
  const locale = useLocale();
  return (
    <select
      aria-label={{t("label")}}
      value={{locale}}
      onChange={{(e) => {{
        const {{ pathname, search }} = window.location;
        const first = pathname.split("/")[1];
        const rest = (routing.locales.includes(first) ? pathname.slice(first.length + 1) : pathname) || "/";
        window.location.assign(`/${{e.target.value}}${{rest === "/" ? "" : rest}}${{search}}`);
      }}}}
    >
      {{routing.locales.map((l) => (
        <option key={{l}} value={{l}}>
          {{new Intl.DisplayNames([l], {{ type: "language" }}).of(l)}}
        </option>
      ))}}
    </select>
  );
}}
"#,
        rel_import(dir, &format!("{base}i18n/routing"))
    )
}

/// The expression exported by next.config, and whether the file is CommonJS.
fn config_expr(path: &str, src: &str) -> Option<((u32, u32), bool)> {
    let alloc = Allocator::default();
    let program = parse(&alloc, path, src)?;
    program.body.iter().find_map(|s| match s {
        Statement::ExportDefaultDeclaration(d) => {
            let e = d.declaration.as_expression()?;
            Some(((e.span().start, e.span().end), false))
        }
        Statement::ExpressionStatement(es) => match &es.expression {
            Expression::AssignmentExpression(a)
                if &src[a.left.span().start as usize..a.left.span().end as usize]
                    == "module.exports" =>
            {
                Some(((a.right.span().start, a.right.span().end), true))
            }
            _ => None,
        },
        _ => None,
    })
}

/// Wrap the exported config: `export default nextConfig` -> `export default wrap(nextConfig)`.
fn next_config(
    root: &Path,
    plan: &mut SetupPlan,
    marker: &str,
    wrap: impl Fn(&str) -> String,
    esm_import: Option<&str>,
    cjs_import: Option<&str>,
) {
    let names = [
        "next.config.ts",
        "next.config.mjs",
        "next.config.js",
        "next.config.mts",
        "next.config.cjs",
    ];
    let Some(rel) = exists_any(root, "", &names) else {
        let import = esm_import.map(|i| format!("{i}\n\n")).unwrap_or_default();
        plan.create(
            root,
            "next.config.mjs",
            format!(
                "{import}/** @type {{import('next').NextConfig}} */\nconst nextConfig = {{}};\n\nexport default {};\n",
                wrap("nextConfig")
            ),
        );
        return;
    };
    plan.edit(root, &rel.clone(), |src| {
        if src.contains(marker) {
            return Ok(None);
        }
        let ((s, e), cjs) = config_expr(&rel, src)
            .ok_or("no `export default` / `module.exports` found: wrap your config by hand")?;
        let mut edits = vec![(s, e, wrap(&src[s as usize..e as usize]))];
        match (cjs, esm_import, cjs_import) {
            (false, Some(i), _) => edits.push(import_edit(&rel, src, i).ok_or("does not parse")?),
            (true, _, Some(i)) => edits.push((0, 0, format!("{i}\n"))),
            _ => {}
        }
        Ok(apply_edits(src, edits))
    });
}

#[derive(Default)]
struct LayoutVisitor {
    html_lang: Option<(u32, u32)>,
    body: Option<(u32, u32)>,
    children: Option<(u32, u32)>,
    component: Option<(u32, u32)>,
}

impl<'a> Visit<'a> for LayoutVisitor {
    fn visit_jsx_element(&mut self, it: &JSXElement<'a>) {
        if let JSXElementName::Identifier(n) = &it.opening_element.name {
            if n.name == "html" {
                for a in &it.opening_element.attributes {
                    if let JSXAttributeItem::Attribute(a) = a
                        && matches!(&a.name, JSXAttributeName::Identifier(i) if i.name == "lang")
                        && let Some(v @ JSXAttributeValue::StringLiteral(_)) = &a.value
                    {
                        self.html_lang = Some((v.span().start, v.span().end));
                    }
                }
            }
            if n.name == "body"
                && self.body.is_none()
                && let Some(c) = &it.closing_element
            {
                self.body = Some((it.opening_element.span.end, c.span.start));
            }
        }
        if let JSXElementName::IdentifierReference(n) = &it.opening_element.name
            && n.name == "Component"
            && self.component.is_none()
        {
            self.component = Some((it.span.start, it.span.end));
        }
        walk::walk_jsx_element(self, it);
    }
    fn visit_jsx_expression_container(&mut self, it: &JSXExpressionContainer<'a>) {
        if let Some(Expression::Identifier(id)) = it.expression.as_expression()
            && id.name == "children"
            && self.children.is_none()
        {
            self.children = Some((it.span.start, it.span.end));
        }
        walk::walk_jsx_expression_container(self, it);
    }
}

fn scan_layout(path: &str, src: &str) -> Option<LayoutVisitor> {
    let alloc = Allocator::default();
    let program = parse(&alloc, path, src)?;
    let mut v = LayoutVisitor::default();
    v.visit_program(&program);
    Some(v)
}

/// Wrap `<body>`'s children (or `{children}`) in `open`/`close`, keeping the indentation.
fn wrap_children(
    src: &str,
    v: &LayoutVisitor,
    open: &str,
    close: &str,
) -> Option<Vec<(u32, u32, String)>> {
    if let Some((s, e)) = v.body {
        let inner = &src[s as usize..e as usize];
        let lead = &inner[..inner.len() - inner.trim_start().len()];
        let trail = inner.len() - inner.trim_end().len();
        return Some(if lead.contains('\n') {
            let indent = lead.rsplit('\n').next().unwrap_or("");
            vec![
                (s, s, format!("\n{indent}{open}")),
                (
                    e - trail as u32,
                    e - trail as u32,
                    format!("\n{indent}{close}"),
                ),
            ]
        } else {
            vec![(s, s, open.into()), (e, e, close.into())]
        });
    }
    let (s, e) = v.children?;
    Some(vec![(s, s, open.into()), (e, e, close.into())])
}

pub fn app(root: &Path, p: &Project, o: &Opts, plan: &mut SetupPlan) {
    let b = p.base;
    let i18n = format!("{b}i18n");
    plan.create(root, &format!("{i18n}/routing.ts"), routing_ts(o));
    plan.create(root, &format!("{i18n}/request.ts"), request_ts(&i18n, o));
    plan.create(root, &format!("{i18n}/proxy.ts"), PROXY_TS.into());
    match exists_any(
        root,
        b,
        &["proxy.ts", "proxy.js", "middleware.ts", "middleware.js"],
    ) {
        None => {
            let (file, name) = if p.next_major >= 16 {
                ("proxy.ts", "proxy")
            } else {
                ("middleware.ts", "middleware")
            };
            plan.create(root, &format!("{b}{file}"), root_proxy(name));
        }
        Some(f) => {
            if !std::fs::read_to_string(root.join(&f))
                .unwrap_or_default()
                .contains("i18nProxy")
            {
                plan.notes.push(format!(
                    "{f} exists: return `i18nProxy(req)` (from ./i18n/proxy) from it for locale prefixes"
                ));
            }
        }
    }
    next_config(
        root,
        plan,
        "next-intl/plugin",
        |e| format!("createNextIntlPlugin()({e})"),
        Some(r#"import createNextIntlPlugin from "next-intl/plugin";"#),
        Some(r#"const createNextIntlPlugin = require("next-intl/plugin");"#),
    );
    if let Some(layout) = exists_any(
        root,
        b,
        &[
            "app/layout.tsx",
            "app/layout.jsx",
            "app/layout.js",
            "app/layout.ts",
        ],
    ) {
        plan.edit(root, &layout.clone(), |src| {
            if src.contains("NextIntlClientProvider") {
                return Ok(None);
            }
            if src.trim_start().starts_with("\"use client\"")
                || src.trim_start().starts_with("'use client'")
            {
                return Err("client layout: wrap it in <NextIntlClientProvider> by hand".into());
            }
            let v = scan_layout(&layout, src).ok_or("does not parse")?;
            let mut edits = wrap_children(
                src,
                &v,
                "<NextIntlClientProvider>",
                "</NextIntlClientProvider>",
            )
            .ok_or("no <body> or {children}: wrap your app in <NextIntlClientProvider> by hand")?;
            let is_async = src.contains("export default async function");
            let mut import = "import { NextIntlClientProvider } from \"next-intl\";".to_string();
            if let Some((s, e)) = v.html_lang {
                if is_async {
                    edits.push((s, e, "{await getLocale()}".into()));
                    import.push_str("\nimport { getLocale } from \"next-intl/server\";");
                } else {
                    edits.push((s, e, "{useLocale()}".into()));
                    import =
                        "import { NextIntlClientProvider, useLocale } from \"next-intl\";".into();
                }
            }
            let wrapped = apply_edits(src, edits).ok_or("overlapping edits")?;
            Ok(add_import(&layout, &wrapped, &import))
        });
    }
    if o.switcher {
        let dir = format!("{b}components");
        plan.create(
            root,
            &format!("{dir}/LocaleSwitcher.tsx"),
            app_switcher(&dir, b),
        );
    }
}

fn ident(l: &str) -> String {
    l.replace(|c: char| !c.is_ascii_alphanumeric(), "_")
}

pub fn pages(root: &Path, p: &Project, o: &Opts, plan: &mut SetupPlan) {
    let b = p.base;
    let dir = format!("{b}i18n");
    let imports: String = o
        .locales
        .iter()
        .map(|l| {
            format!(
                "import {} from \"{}\";\n",
                ident(l),
                rel_import(&dir, &o.catalog.replace("{locale}", l))
            )
        })
        .collect();
    let map: Vec<String> = o
        .locales
        .iter()
        .map(|l| format!("{l:?}: {}", ident(l)))
        .collect();
    plan.create(
        root,
        &format!("{dir}/provider.tsx"),
        format!(
            r#"import {{ NextIntlClientProvider }} from "next-intl";
import {{ useRouter }} from "next/router";
import type {{ ReactNode }} from "react";
{imports}
// Generated by `glot i18nize`. Locales mirror glot.toml; routing is Next's built-in `i18n` (next.config).
const MESSAGES: Record<string, Record<string, unknown>> = {{ {} }};

export function I18nProvider({{ children }}: {{ children: ReactNode }}) {{
  const {{ locale = "{src}", defaultLocale = "{src}" }} = useRouter();
  return (
    <NextIntlClientProvider locale={{locale}} messages={{MESSAGES[locale] ?? MESSAGES[defaultLocale]}} timeZone="UTC">
      {{children}}
    </NextIntlClientProvider>
  );
}}
"#,
            map.join(", "),
            src = o.locales[0]
        ),
    );
    empty_catalogs(root, o, plan);
    let locales = locales_list(o);
    let src_locale = o.locales[0].clone();
    next_config(
        root,
        plan,
        "defaultLocale",
        move |e| {
            format!(
                "{{ ...({e}), i18n: {{ locales: {locales}, defaultLocale: \"{src_locale}\" }} }}"
            )
        },
        None,
        None,
    );
    if o.routing == Routing::Cookie {
        plan.notes.push(
            "Pages Router: Next's built-in i18n routing prefixes non-default locales (/fr/...)"
                .into(),
        );
    }
    let provider = rel_import(&format!("{b}pages"), &format!("{dir}/provider"));
    let import = format!("import {{ I18nProvider }} from \"{provider}\";");
    match exists_any(
        root,
        b,
        &["pages/_app.tsx", "pages/_app.jsx", "pages/_app.js"],
    ) {
        Some(app) => plan.edit(root, &app.clone(), |src| {
            if src.contains("I18nProvider") {
                return Ok(None);
            }
            let v = scan_layout(&app, src).ok_or("does not parse")?;
            let (s, e) = v
                .component
                .ok_or("no <Component {...pageProps} />: wrap it in <I18nProvider> by hand")?;
            let wrapped = apply_edits(
                src,
                vec![
                    (s, s, "<I18nProvider>".into()),
                    (e, e, "</I18nProvider>".into()),
                ],
            )
            .ok_or("overlapping edits")?;
            Ok(add_import(&app, &wrapped, &import))
        }),
        None => plan.create(
            root,
            &format!("{b}pages/_app.tsx"),
            format!(
                r#"import type {{ AppProps }} from "next/app";
{import}

export default function App({{ Component, pageProps }}: AppProps) {{
  return (
    <I18nProvider>
      <Component {{...pageProps}} />
    </I18nProvider>
  );
}}
"#
            ),
        ),
    }
    if o.switcher {
        plan.create(
            root,
            &format!("{b}components/LocaleSwitcher.tsx"),
            r#"import { useTranslations } from "next-intl";
import { useRouter } from "next/router";

/** Language picker generated by `glot i18nize --switcher`: drop it in a header or menu. */
export function LocaleSwitcher() {
  const t = useTranslations("locale_switcher");
  const router = useRouter();
  return (
    <select
      aria-label={t("label")}
      value={router.locale}
      onChange={(e) => router.push(router.asPath, router.asPath, { locale: e.target.value })}
    >
      {(router.locales ?? []).map((l) => (
        <option key={l} value={l}>
          {new Intl.DisplayNames([l], { type: "language" }).of(l)}
        </option>
      ))}
    </select>
  );
}
"#
            .into(),
        );
    }
}
