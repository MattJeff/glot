//! react-i18next wiring (Vite, Remix / React Router, Astro islands): `i18n.ts` + import in the entry.
use std::path::Path;

use super::{
    Framework, Opts, Project, SetupPlan, add_import, empty_catalogs, exists_any, rel_import,
};

fn ident(l: &str) -> String {
    format!("l_{}", l.replace(|c: char| !c.is_ascii_alphanumeric(), "_"))
}

fn i18n_ts(dir: &str, o: &Opts) -> String {
    let imports: String = o
        .locales
        .iter()
        .map(|l| {
            format!(
                "import {} from \"{}\";\n",
                ident(l),
                rel_import(dir, &o.catalog.replace("{locale}", l))
            )
        })
        .collect();
    let resources: Vec<String> = o
        .locales
        .iter()
        .map(|l| format!("{l:?}: {{ translation: {} }}", ident(l)))
        .collect();
    format!(
        r#"// Generated by `glot i18nize`. Locales mirror glot.toml (source locale first).
import i18n from "i18next";
import {{ initReactI18next }} from "react-i18next";
{imports}
export const LOCALES = {};
const STORAGE_KEY = "glot-locale";

// ?lng= or the URL prefix (/fr/...), then the saved choice, then the browser language.
// ponytail: server rendering (Remix, Astro) always uses the source locale.
function detect(): string {{
  if (typeof window === "undefined") return LOCALES[0];
  const candidates = [
    new URLSearchParams(window.location.search).get("lng"),
    window.location.pathname.split("/")[1],
    window.localStorage.getItem(STORAGE_KEY),
    ...navigator.languages.map((l) => l.split("-")[0]),
  ];
  return candidates.find((l): l is string => !!l && LOCALES.includes(l)) ?? LOCALES[0];
}}

export function setLocale(locale: string) {{
  window.localStorage.setItem(STORAGE_KEY, locale);
  return i18n.changeLanguage(locale);
}}

i18n.use(initReactI18next).init({{
  resources: {{ {} }},
  lng: detect(),
  fallbackLng: LOCALES[0],
  interpolation: {{ escapeValue: false }},
}});

export default i18n;
"#,
        serde_json::to_string(&o.locales).unwrap(),
        resources.join(", ")
    )
}

fn import_i18n(plan: &mut SetupPlan, root: &Path, file: &str, i18n: &str) {
    let dir = file.rsplit_once('/').map_or("", |(d, _)| d);
    let spec = rel_import(dir, i18n);
    let line = format!("import \"{spec}\";");
    plan.edit(root, file, |src| {
        if src.contains(&line) {
            return Ok(None);
        }
        Ok(add_import(file, src, &line))
    });
}

pub fn setup(root: &Path, p: &Project, o: &Opts, plan: &mut SetupPlan) {
    let dir = p.base.trim_end_matches('/');
    let i18n = format!("{dir}/i18n");
    plan.create(root, &format!("{i18n}.ts"), i18n_ts(dir, o));
    empty_catalogs(root, o, plan);
    match p.framework {
        Framework::Vite => match exists_any(
            root,
            "src/",
            &[
                "main.tsx",
                "main.jsx",
                "main.ts",
                "main.js",
                "index.tsx",
                "index.jsx",
            ],
        ) {
            Some(entry) => import_i18n(plan, root, &entry, &i18n),
            None => plan
                .notes
                .push("no src/main.tsx: add `import \"./i18n\";` to your entry".into()),
        },
        Framework::Remix => match exists_any(root, "app/", &["root.tsx", "root.jsx"]) {
            Some(entry) => import_i18n(plan, root, &entry, &i18n),
            None => plan
                .notes
                .push("no app/root.tsx: import ./i18n in your root".into()),
        },
        // Islands hydrate separately: each translated component imports the init itself.
        _ => {
            let mut files = vec![];
            collect(root, Path::new(dir), &mut files);
            for f in files {
                let src = std::fs::read_to_string(root.join(&f)).unwrap_or_default();
                if src.contains("from \"react-i18next\"") && !f.ends_with("/i18n.ts") {
                    import_i18n(plan, root, &f, &i18n);
                }
            }
        }
    }
    if o.switcher {
        let cdir = format!("{dir}/components");
        plan.create(
            root,
            &format!("{cdir}/LocaleSwitcher.tsx"),
            format!(
                r#"import {{ useTranslation }} from "react-i18next";
import {{ LOCALES, setLocale }} from "{}";

/** Language picker generated by `glot i18nize --switcher`: drop it in a header or menu. */
export function LocaleSwitcher() {{
  const {{ t, i18n }} = useTranslation();
  return (
    <select aria-label={{t("locale_switcher.label")}} value={{i18n.language}} onChange={{(e) => setLocale(e.target.value)}}>
      {{LOCALES.map((l) => (
        <option key={{l}} value={{l}}>
          {{new Intl.DisplayNames([l], {{ type: "language" }}).of(l)}}
        </option>
      ))}}
    </select>
  );
}}
"#,
                rel_import(&cdir, &i18n)
            ),
        );
    }
}

/// `.tsx` / `.jsx` files under `dir` (relative to root), skipping node_modules.
fn collect(root: &Path, dir: &Path, out: &mut Vec<String>) {
    for e in std::fs::read_dir(root.join(dir))
        .into_iter()
        .flatten()
        .flatten()
    {
        let rel = dir.join(e.file_name());
        let name = e.file_name().to_string_lossy().to_string();
        if e.path().is_dir() && name != "node_modules" && !name.starts_with('.') {
            collect(root, &rel, out);
        } else if name.ends_with(".tsx") || name.ends_with(".jsx") {
            out.push(rel.to_string_lossy().replace('\\', "/"));
        }
    }
    out.sort();
}
