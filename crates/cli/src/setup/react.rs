//! react-i18next wiring (Vite, Remix / React Router, Astro islands): `i18n.ts` + import in the entry.
use std::path::Path;

use oxc_ast::ast::{Expression, Statement};
use oxc_span::GetSpan;

use super::{
    Framework, Opts, Project, SetupPlan, add_import, empty_catalogs, exists_any, refactor,
    rel_import,
};

fn ident(l: &str) -> String {
    format!("l_{}", l.replace(|c: char| !c.is_ascii_alphanumeric(), "_"))
}

/// How the browser picks the locale; with server rendering it must be the one the server used.
#[derive(Clone, Copy, PartialEq)]
enum Mode {
    /// Vite SPA: `?lng=`, URL prefix, saved choice, browser language.
    Spa,
    /// React Router: the server (remix-i18next middleware) decides; the choice is a cookie.
    Router,
    /// Astro: native i18n routing, the locale is the URL prefix (`/fr/...`).
    Astro,
}

const SPA_DETECT: &str = r#"// ?lng= or the URL prefix (/fr/...), then the saved choice, then the browser language.
function detect(): string {
  if (typeof window === "undefined") return LOCALES[0];
  const candidates = [
    new URLSearchParams(window.location.search).get("lng"),
    window.location.pathname.split("/")[1],
    window.localStorage.getItem(STORAGE_KEY),
    ...navigator.languages.map((l) => l.split("-")[0]),
  ];
  return candidates.find((l): l is string => !!l && LOCALES.includes(l)) ?? LOCALES[0];
}"#;

const SSR_DETECT: &str = r#"// The browser hydrates with the locale the server rendered: <html lang>, else the URL prefix.
function detect(): string {
  if (typeof window === "undefined") return LOCALES[0];
  const candidates = [document.documentElement.lang, window.location.pathname.split("/")[1]];
  return candidates.find((l) => LOCALES.includes(l)) ?? LOCALES[0];
}"#;

const SPA_SET: &str = r#"
export function setLocale(locale: string) {
  window.localStorage.setItem(STORAGE_KEY, locale);
  return i18n.changeLanguage(locale);
}"#;

const ROUTER_SET: &str = r#"
// The server renders each request with its own instance (middleware/i18next.ts): it reads
// ?lng=, this cookie, then Accept-Language.
export function setLocale(locale: string) {
  document.cookie = `${STORAGE_KEY}=${locale}; path=/; max-age=31536000; samesite=lax`;
  return i18n.changeLanguage(locale);
}"#;

const ASTRO_SET: &str = r#"
// Astro i18n routing: the default locale has no prefix, the others live under /fr/...
export function setLocale(locale: string) {
  const [, first, ...rest] = window.location.pathname.split("/");
  const path = "/" + (LOCALES.includes(first) ? rest : [first, ...rest]).join("/");
  window.location.assign((locale === LOCALES[0] ? "" : `/${locale}`) + path);
}"#;

fn i18n_ts(dir: &str, o: &Opts, mode: Mode) -> String {
    let imports: String = o
        .locales
        .iter()
        .map(|l| {
            format!(
                "import {} from \"{}\";\n",
                ident(l),
                rel_import(dir, &o.catalog.replace("{locale}", l))
            )
        })
        .collect();
    let resources: Vec<String> = o
        .locales
        .iter()
        .map(|l| format!("{l:?}: {{ translation: {} }}", ident(l)))
        .collect();
    let detect = if mode == Mode::Spa {
        SPA_DETECT
    } else {
        SSR_DETECT
    };
    let set = match mode {
        Mode::Spa => SPA_SET,
        Mode::Router => ROUTER_SET,
        Mode::Astro => ASTRO_SET,
    };
    format!(
        r#"// Generated by `glot i18nize`. Locales mirror glot.toml (source locale first).
import i18n from "i18next";
import {{ initReactI18next }} from "react-i18next";
{imports}
export const LOCALES = {};
export const resources = {{ {} }};
const STORAGE_KEY = "glot-locale";

{detect}
{set}

i18n.use(initReactI18next).init({{
  resources,
  lng: detect(),
  fallbackLng: LOCALES[0],
  interpolation: {{ escapeValue: false }},
}});
if (typeof document !== "undefined") i18n.on("languageChanged", (l) => (document.documentElement.lang = l));

export default i18n;
"#,
        serde_json::to_string(&o.locales).unwrap(),
        resources.join(", ")
    )
}

fn middleware_ts(rr_major: u32) -> String {
    let module = if rr_major >= 8 {
        "remix-i18next"
    } else {
        "remix-i18next/middleware"
    };
    format!(
        r#"// Generated by `glot i18nize`: one i18next instance per request, locale from ?lng=, the
// `glot-locale` cookie (LocaleSwitcher), then Accept-Language. Wired in root.tsx and entry.server.tsx.
import {{ initReactI18next }} from "react-i18next";
import {{ createI18nextMiddleware }} from "{module}";
import {{ LOCALES, resources }} from "../i18n";

export const [i18nextMiddleware, getLocale, getInstance] = createI18nextMiddleware({{
  detection: {{
    supportedLanguages: LOCALES,
    fallbackLanguage: LOCALES[0],
    order: ["searchParams", "custom", "header"],
    async findLocale({{ request }}) {{
      return request.headers.get("Cookie")?.match(/(?:^|;\s*)glot-locale=([^;]+)/)?.[1] ?? null;
    }},
  }},
  i18next: {{ resources, fallbackLng: LOCALES[0], interpolation: {{ escapeValue: false }} }},
  plugins: [initReactI18next],
}});
"#
    )
}

/// React Router's default `entry.server.tsx` (node), rendering inside the request's i18next instance.
const ENTRY_SERVER: &str = r#"import { PassThrough } from "node:stream";

import type { EntryContext, RouterContextProvider } from "react-router";
import { createReadableStreamFromReadable } from "@react-router/node";
import { ServerRouter } from "react-router";
import { isbot } from "isbot";
import type { RenderToPipeableStreamOptions } from "react-dom/server";
import { renderToPipeableStream } from "react-dom/server";
import { I18nextProvider } from "react-i18next";
import i18n from "./i18n";
import { getInstance } from "./middleware/i18next";

export const streamTimeout = 5_000;

// Generated by `glot i18nize` from React Router's default entry: only <I18nextProvider> was added.
export default function handleRequest(
  request: Request,
  responseStatusCode: number,
  responseHeaders: Headers,
  routerContext: EntryContext,
  loadContext: RouterContextProvider,
) {
  if (request.method.toUpperCase() === "HEAD") {
    return new Response(null, { status: responseStatusCode, headers: responseHeaders });
  }

  return new Promise((resolve, reject) => {
    let shellRendered = false;
    const userAgent = request.headers.get("user-agent");
    const readyOption: keyof RenderToPipeableStreamOptions =
      (userAgent && isbot(userAgent)) || routerContext.isSpaMode ? "onAllReady" : "onShellReady";
    let timeoutId: ReturnType<typeof setTimeout> | undefined = setTimeout(() => abort(), streamTimeout + 1000);

    const { pipe, abort } = renderToPipeableStream(
      <I18nextProvider i18n={instance(loadContext)}>
        <ServerRouter context={routerContext} url={request.url} />
      </I18nextProvider>,
      {
        [readyOption]() {
          shellRendered = true;
          const body = new PassThrough({
            final(callback) {
              clearTimeout(timeoutId);
              timeoutId = undefined;
              callback();
            },
          });
          const stream = createReadableStreamFromReadable(body);
          responseHeaders.set("Content-Type", "text/html");
          pipe(body);
          resolve(new Response(stream, { headers: responseHeaders, status: responseStatusCode }));
        },
        onShellError(error: unknown) {
          reject(error);
        },
        onError(error: unknown) {
          responseStatusCode = 500;
          if (shellRendered) console.error(error);
        },
      },
    );
  });
}

// The request's instance (middleware/i18next.ts); the shared one when the middleware did not run.
function instance(context: RouterContextProvider) {
  try {
    return getInstance(context);
  } catch {
    return i18n;
  }
}
"#;

const ASTRO_MIDDLEWARE: &str = r#"// Generated by `glot i18nize`: render the React islands in the page's locale (Astro i18n routing).
// ponytail: one shared i18next instance, safe for static builds (pages render one at a time); with
// on-demand rendering, concurrent requests in different locales can race: pass the locale as a prop then.
import { defineMiddleware } from "astro:middleware";
import i18n, { LOCALES } from "./i18n";

export const onRequest = defineMiddleware(async (ctx, next) => {
  const locale = ctx.currentLocale ?? LOCALES[0];
  if (i18n.language !== locale) await i18n.changeLanguage(locale);
  return next();
});
"#;

fn import_i18n(plan: &mut SetupPlan, root: &Path, file: &str, i18n: &str) {
    let dir = file.rsplit_once('/').map_or("", |(d, _)| d);
    let spec = rel_import(dir, i18n);
    let line = format!("import \"{spec}\";");
    plan.edit(root, file, |src| {
        // `import { LOCALES } from "../i18n"` runs the init too.
        if src.contains(&line) || src.contains(&format!("from \"{spec}\"")) {
            return Ok(None);
        }
        Ok(add_import(file, src, &line))
    });
}

/// `<html lang="en">` -> `<html lang={expr}>`, or add the attribute.
pub(super) fn html_lang(src: &str, expr: &str) -> Option<String> {
    let start = src.find("<html")?;
    let end = start + src[start..].find('>')?;
    let tag = &src[start..end];
    let new = match tag.find("lang=") {
        Some(i) => {
            let v = &tag[i + 5..];
            let len = match v.chars().next()? {
                q @ ('"' | '\'') => v[1..].find(q)? + 2,
                _ => return None,
            };
            format!("{}lang={{{expr}}}{}", &tag[..i], &v[len..])
        }
        None => format!("<html lang={{{expr}}}{}", &tag[5..]),
    };
    Some(format!("{}{new}{}", &src[..start], &src[end..]))
}

/// root.tsx: register the middleware and render `<html lang>` from the request's instance.
fn router_root(root: &Path, plan: &mut SetupPlan, file: &str) {
    plan.edit(root, file, |src| {
        if src.contains("i18nextMiddleware") {
            return Ok(None);
        }
        if src.contains("export const middleware") || src.contains("export { middleware") {
            return Err("already exports `middleware`: add `i18nextMiddleware` (from ./middleware/i18next) to it".into());
        }
        let mut out = src.to_string();
        // ponytail: no `lang` literal on <html>: the client falls back to the URL prefix.
        if let Some((s, e)) = super::next::scan_layout(file, src).and_then(|v| v.html_lang) {
            out = refactor::apply_edits(
                src,
                vec![(s, e, "{useTranslation().i18n.language}".into())],
            )
            .ok_or("overlapping edits")?;
            if !src.contains("useTranslation") {
                out = add_import(file, &out, "import { useTranslation } from \"react-i18next\";")
                    .ok_or("does not parse")?;
            }
        }
        let out = add_import(
            file,
            &out,
            "import { i18nextMiddleware } from \"./middleware/i18next\";",
        )
        .ok_or("does not parse")?;
        Ok(Some(format!(
            "{}\n\n// Detects the request's locale and gives the render its own i18next instance.\nexport const middleware = [i18nextMiddleware];\n",
            out.trim_end()
        )))
    });
}

/// `defineConfig({ ... })` / `export default { ... }` in astro.config: add the `i18n` block.
fn astro_config(root: &Path, plan: &mut SetupPlan, o: &Opts) {
    let Some(rel) = exists_any(
        root,
        "",
        &[
            "astro.config.mjs",
            "astro.config.ts",
            "astro.config.js",
            "astro.config.mts",
        ],
    ) else {
        plan.notes
            .push("no astro.config.mjs: add the `i18n` routing config by hand".into());
        return;
    };
    let fallback: Vec<String> = o.locales[1..]
        .iter()
        .map(|l| format!("{l:?}: {:?}", o.locales[0]))
        .collect();
    let block = format!(
        "i18n: {{\n    locales: {},\n    defaultLocale: {:?},\n    // Pages are written once: /fr/... renders them in French (glot i18nize).\n    fallback: {{ {} }},\n    routing: {{ prefixDefaultLocale: false, fallbackType: \"rewrite\" }},\n  }}",
        serde_json::to_string(&o.locales).unwrap(),
        o.locales[0],
        fallback.join(", ")
    );
    plan.edit(root, &rel.clone(), |src| {
        if src.contains("i18n:") || src.contains("i18n,") {
            return match o.locales.iter().all(|l| src.contains(&format!("{l:?}"))) {
                true => Ok(None),
                false => Err("its `i18n` block misses locales from glot.toml: add them".into()),
            };
        }
        let alloc = oxc_allocator::Allocator::default();
        let program = refactor::parse(&alloc, &rel, src).ok_or("does not parse")?;
        let obj = program
            .body
            .iter()
            .find_map(|s| match s {
                Statement::ExportDefaultDeclaration(d) => {
                    match d.declaration.as_expression()?.get_inner_expression() {
                        Expression::ObjectExpression(o) => Some(o),
                        Expression::CallExpression(c) => {
                            match c.arguments.first()?.as_expression()? {
                                Expression::ObjectExpression(o) => Some(o),
                                _ => None,
                            }
                        }
                        _ => None,
                    }
                }
                _ => None,
            })
            .ok_or("no `export default defineConfig({ ... })`: add the `i18n` block by hand")?;
        let edit = match obj.properties.last() {
            Some(p) => {
                let end = p.span().end;
                let indent = refactor::line_indent(src, p.span().start);
                (
                    end,
                    end,
                    format!(
                        ",\n{indent}{}",
                        block.replace("\n  ", &format!("\n{indent}"))
                    ),
                )
            }
            None => (
                obj.span.start + 1,
                obj.span.start + 1,
                format!("\n  {block},\n"),
            ),
        };
        Ok(refactor::apply_edits(src, vec![edit]))
    });
}

pub fn setup(root: &Path, p: &Project, o: &Opts, plan: &mut SetupPlan) {
    let dir = p.base.trim_end_matches('/');
    let i18n = format!("{dir}/i18n");
    // Remix v2 (`@remix-run/react`) keeps client-side detection only.
    let router = p.framework == Framework::Remix && p.rr_major >= 7;
    let mode = match p.framework {
        Framework::Astro => Mode::Astro,
        _ if router => Mode::Router,
        _ => Mode::Spa,
    };
    plan.create(root, &format!("{i18n}.ts"), i18n_ts(dir, o, mode));
    empty_catalogs(root, o, plan);
    match p.framework {
        Framework::Vite => match exists_any(
            root,
            "src/",
            &[
                "main.tsx",
                "main.jsx",
                "main.ts",
                "main.js",
                "index.tsx",
                "index.jsx",
            ],
        ) {
            Some(entry) => import_i18n(plan, root, &entry, &i18n),
            None => plan
                .notes
                .push("no src/main.tsx: add `import \"./i18n\";` to your entry".into()),
        },
        Framework::Remix => match exists_any(root, "app/", &["root.tsx", "root.jsx"]) {
            Some(entry) => {
                import_i18n(plan, root, &entry, &i18n);
                if router {
                    react_router(root, p, plan, &entry);
                } else {
                    plan.notes.push(
                        "Remix v2: the server renders the source locale; see remix-i18next v6 for SSR".into(),
                    );
                }
            }
            None => plan
                .notes
                .push("no app/root.tsx: import ./i18n in your root".into()),
        },
        // Islands hydrate separately: each translated component imports the init itself.
        _ => {
            let mut files = vec![];
            collect(root, Path::new(dir), &mut files);
            for f in files {
                let src = std::fs::read_to_string(root.join(&f)).unwrap_or_default();
                if src.contains("from \"react-i18next\"") && !f.ends_with("/i18n.ts") {
                    import_i18n(plan, root, &f, &i18n);
                }
            }
            astro_config(root, plan, o);
            match exists_any(
                root,
                "src/",
                &[
                    "middleware.ts",
                    "middleware.js",
                    "middleware/index.ts",
                    "middleware/index.js",
                ],
            ) {
                None => plan.create(root, "src/middleware.ts", ASTRO_MIDDLEWARE.into()),
                Some(f) => {
                    if !std::fs::read_to_string(root.join(&f))
                        .unwrap_or_default()
                        .contains("changeLanguage")
                    {
                        plan.notes.push(format!(
                            "{f} exists: call `i18n.changeLanguage(ctx.currentLocale)` (from ./i18n) in it before `next()`"
                        ));
                    }
                }
            }
            let mut astro = vec![];
            collect_ext(root, Path::new(dir), ".astro", &mut astro);
            for f in astro {
                plan.edit(root, &f.clone(), |src| {
                    if !src.contains("<html") || src.contains("Astro.currentLocale") {
                        return Ok(None);
                    }
                    Ok(html_lang(src, "Astro.currentLocale"))
                });
            }
        }
    }
    if o.switcher {
        let cdir = format!("{dir}/components");
        plan.create(
            root,
            &format!("{cdir}/LocaleSwitcher.tsx"),
            format!(
                r#"import {{ useTranslation }} from "react-i18next";
import {{ LOCALES, setLocale }} from "{}";

/** Language picker generated by `glot i18nize --switcher`: drop it in a header or menu. */
export function LocaleSwitcher() {{
  const {{ t, i18n }} = useTranslation();
  return (
    <select aria-label={{t("locale_switcher.label")}} value={{i18n.language}} onChange={{(e) => setLocale(e.target.value)}}>
      {{LOCALES.map((l) => (
        <option key={{l}} value={{l}}>
          {{new Intl.DisplayNames([l], {{ type: "language" }}).of(l)}}
        </option>
      ))}}
    </select>
  );
}}
"#,
                rel_import(&cdir, &i18n)
            ),
        );
    }
}

/// React Router framework mode: remix-i18next middleware + per-request instance in entry.server.
fn react_router(root: &Path, p: &Project, plan: &mut SetupPlan, root_file: &str) {
    let need = |plan: &mut SetupPlan, pkg: &str, spec: String| {
        if !p.deps.contains(pkg) {
            plan.packages.push(spec);
        }
    };
    need(
        plan,
        "remix-i18next",
        format!("remix-i18next@^{}", p.rr_major.min(8)),
    );
    plan.create(root, "app/middleware/i18next.ts", middleware_ts(p.rr_major));
    router_root(root, plan, root_file);
    match exists_any(
        root,
        "app/",
        &[
            "entry.server.tsx",
            "entry.server.jsx",
            "entry.server.ts",
            "entry.server.js",
        ],
    ) {
        None => {
            plan.create(root, "app/entry.server.tsx", ENTRY_SERVER.into());
            need(plan, "isbot", "isbot@^5".into());
            need(
                plan,
                "@react-router/node",
                format!("@react-router/node@^{}", p.rr_major),
            );
        }
        Some(f) => {
            if !std::fs::read_to_string(root.join(&f))
                .unwrap_or_default()
                .contains("I18nextProvider")
            {
                plan.notes.push(format!(
                    "{f} exists: wrap <ServerRouter /> in <I18nextProvider i18n={{getInstance(loadContext)}}> (getInstance from ./middleware/i18next)"
                ));
            }
        }
    }
    if p.rr_major == 7 {
        router_config_v8_middleware(root, plan);
    }
}

/// React Router 7 runs middleware behind `future.v8_middleware`.
fn router_config_v8_middleware(root: &Path, plan: &mut SetupPlan) {
    let Some(rel) = exists_any(
        root,
        "",
        &["react-router.config.ts", "react-router.config.js"],
    ) else {
        plan.create(
            root,
            "react-router.config.ts",
            "import type { Config } from \"@react-router/dev/config\";\n\nexport default {\n  future: { v8_middleware: true },\n} satisfies Config;\n".into(),
        );
        return;
    };
    plan.edit(root, &rel.clone(), |src| {
        if src.contains("v8_middleware") {
            return Ok(None);
        }
        if src.contains("future") {
            return Err("set `future.v8_middleware: true` (remix-i18next needs middleware)".into());
        }
        let i = src
            .find("export default {")
            .ok_or("no `export default {`: set `future.v8_middleware: true` by hand")?
            + "export default {".len();
        Ok(Some(format!(
            "{}\n  future: {{ v8_middleware: true }},{}",
            &src[..i],
            &src[i..]
        )))
    });
}

/// `.tsx` / `.jsx` files under `dir` (relative to root), skipping node_modules.
fn collect(root: &Path, dir: &Path, out: &mut Vec<String>) {
    collect_ext(root, dir, ".tsx", out);
    collect_ext(root, dir, ".jsx", out);
}

fn collect_ext(root: &Path, dir: &Path, ext: &str, out: &mut Vec<String>) {
    for e in std::fs::read_dir(root.join(dir))
        .into_iter()
        .flatten()
        .flatten()
    {
        let rel = dir.join(e.file_name());
        let name = e.file_name().to_string_lossy().to_string();
        if e.path().is_dir() && name != "node_modules" && !name.starts_with('.') {
            collect_ext(root, &rel, ext, out);
        } else if name.ends_with(ext) {
            out.push(rel.to_string_lossy().replace('\\', "/"));
        }
    }
    out.sort();
}
