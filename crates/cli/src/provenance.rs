//! `glot provenance`: who/what produced each translation, from glot.lock (EU AI Act art. 50 transparency).
use anyhow::Result;
use clap::{Subcommand, ValueEnum};
use serde::Serialize;
use std::process::ExitCode;

use glot_core::lock::{Lockfile, Origin};

use crate::style::*;

#[derive(Subcommand)]
pub enum ProvenanceCmd {
    /// Per key and locale: machine (model, date) / human / reviewed (by whom, when), judge score.
    Export {
        #[arg(long, value_enum, default_value_t = Fmt::Json)]
        format: Fmt,
        /// Write to this file instead of stdout.
        #[arg(long, short)]
        out: Option<std::path::PathBuf>,
    },
    /// Write `{locale}.provenance.json` next to each catalog, for the runtime badge (`@glot/runtime/provenance`).
    Catalog,
}

#[derive(Clone, Copy, ValueEnum)]
pub enum Fmt {
    Json,
    Csv,
    Html,
}

#[derive(Debug, Serialize, PartialEq)]
pub struct Row {
    pub locale: String,
    pub key: String,
    /// machine | human | imported
    pub origin: &'static str,
    /// Produced by an AI model and not reviewed by a human since.
    pub ai_generated: bool,
    pub model: Option<String>,
    pub translated_at: Option<String>,
    pub reviewed: bool,
    pub reviewed_at: Option<String>,
    pub reviewed_by: Option<String>,
    pub score: Option<u8>,
}

pub fn rows(lock: &Lockfile) -> Vec<Row> {
    let mut out = vec![];
    for (locale, entries) in &lock.entries {
        for (key, e) in entries {
            let (origin, model) = match &e.origin {
                Origin::Machine { model } => ("machine", Some(model.clone())),
                Origin::Human => ("human", None),
                Origin::Imported => ("imported", None),
            };
            out.push(Row {
                locale: locale.clone(),
                key: key.clone(),
                origin,
                ai_generated: origin == "machine" && !e.reviewed,
                model,
                translated_at: e.translated_at.clone(),
                reviewed: e.reviewed,
                reviewed_at: e.reviewed_at.clone(),
                reviewed_by: e.reviewed_by.clone(),
                score: e.score,
            });
        }
    }
    out
}

const COLS: [&str; 10] = [
    "locale",
    "key",
    "origin",
    "ai_generated",
    "model",
    "translated_at",
    "reviewed",
    "reviewed_at",
    "reviewed_by",
    "score",
];

fn cells(r: &Row) -> [String; 10] {
    let o = |v: &Option<String>| v.clone().unwrap_or_default();
    [
        r.locale.clone(),
        r.key.clone(),
        r.origin.into(),
        r.ai_generated.to_string(),
        o(&r.model),
        o(&r.translated_at),
        r.reviewed.to_string(),
        o(&r.reviewed_at),
        o(&r.reviewed_by),
        r.score.map(|s| s.to_string()).unwrap_or_default(),
    ]
}

pub fn csv(rows: &[Row]) -> String {
    let esc = |s: &str| {
        if s.contains([',', '"', '\n', '\r']) {
            format!("\"{}\"", s.replace('"', "\"\""))
        } else {
            s.to_string()
        }
    };
    let mut out = COLS.join(",") + "\n";
    for r in rows {
        out += &cells(r)
            .iter()
            .map(|c| esc(c))
            .collect::<Vec<_>>()
            .join(",");
        out += "\n";
    }
    out
}

pub fn html(rows: &[Row]) -> String {
    let esc = |s: &str| {
        s.replace('&', "&amp;")
            .replace('<', "&lt;")
            .replace('>', "&gt;")
            .replace('"', "&quot;")
    };
    let ai = rows.iter().filter(|r| r.ai_generated).count();
    let mut out = format!(
        "<!doctype html>\n<html lang=\"en\"><head><meta charset=\"utf-8\"><meta name=\"viewport\" content=\"width=device-width,initial-scale=1\">\
<title>Translation provenance</title><style>body{{font:14px system-ui,sans-serif;margin:16px;color:#111;background:#fff}}\
table{{border-collapse:collapse;width:100%}}th,td{{border:1px solid #ddd;padding:4px 8px;text-align:left}}th{{background:#f4f4f4}}</style></head><body>\
<h1>Translation provenance</h1><p>Generated by glot from glot.lock on {}. {} entries, {ai} machine-translated and not reviewed by a human.</p>\
<p><small>Informational record of how each translation was produced; it is not a legal assessment.</small></p><table><thead><tr>",
        glot_core::lock::utc_now(),
        rows.len()
    );
    for c in COLS {
        out += &format!("<th>{c}</th>");
    }
    out += "</tr></thead><tbody>\n";
    for r in rows {
        out += "<tr>";
        for c in cells(r) {
            out += &format!("<td>{}</td>", esc(&c));
        }
        out += "</tr>\n";
    }
    out + "</tbody></table></body></html>\n"
}

/// Runtime metadata catalog: `{key: {origin, model?, translated_at?, reviewed, reviewed_at?, reviewed_by?, score?}}`.
pub fn catalog(rows: &[Row], locale: &str) -> serde_json::Value {
    let mut m = serde_json::Map::new();
    for r in rows.iter().filter(|r| r.locale == locale) {
        let mut e = serde_json::json!({"origin": r.origin, "reviewed": r.reviewed});
        for (k, v) in [
            ("model", &r.model),
            ("translated_at", &r.translated_at),
            ("reviewed_at", &r.reviewed_at),
            ("reviewed_by", &r.reviewed_by),
        ] {
            if let Some(v) = v {
                e[k] = v.clone().into();
            }
        }
        if let Some(s) = r.score {
            e["score"] = s.into();
        }
        m.insert(r.key.clone(), e);
    }
    serde_json::Value::Object(m)
}

/// `messages/{locale}.json` -> `messages/{locale}.provenance.json`.
fn catalog_path(pattern: &str, locale: &str) -> String {
    let p = pattern.replace("{locale}", locale);
    match p.strip_suffix(".json") {
        Some(stem) => format!("{stem}.provenance.json"),
        None => format!("{p}.provenance.json"),
    }
}

pub fn run(cmd: ProvenanceCmd) -> Result<ExitCode> {
    let ws = crate::open()?;
    let rows = rows(&ws.lock);
    match cmd {
        ProvenanceCmd::Export { format, out } => {
            let text = match format {
                Fmt::Json => serde_json::to_string_pretty(&rows)? + "\n",
                Fmt::Csv => csv(&rows),
                Fmt::Html => html(&rows),
            };
            match out {
                Some(p) => {
                    std::fs::write(&p, text)?;
                    anstream::eprintln!(
                        "{GREEN}wrote{GREEN:#} {} ({} entries)",
                        p.display(),
                        rows.len()
                    );
                }
                None => print!("{text}"),
            }
        }
        ProvenanceCmd::Catalog => {
            let pattern = ws.config.files.first().cloned().unwrap_or_default();
            if pattern.contains('*') {
                anyhow::bail!(
                    "catalog pattern {pattern:?} has a wildcard: a provenance file next to it would be read as a catalog"
                );
            }
            for loc in &ws.config.target_locales {
                let rel = catalog_path(&pattern, loc);
                let path = ws.root.join(&rel);
                if let Some(d) = path.parent() {
                    std::fs::create_dir_all(d)?;
                }
                std::fs::write(
                    &path,
                    serde_json::to_string_pretty(&catalog(&rows, loc))? + "\n",
                )?;
                anstream::println!("  {GREEN}wrote{GREEN:#}   {rel}");
            }
        }
    }
    Ok(ExitCode::SUCCESS)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn export_formats() {
        let mut lock = Lockfile::default();
        lock.record(
            "fr",
            "a",
            "Hi",
            "Salut",
            Origin::Machine {
                model: "claude-haiku-5-5".into(),
            },
            Some(91),
        );
        lock.record("fr", "b,c", "Bye", "Au revoir", Origin::Human, None);
        let r = rows(&lock);
        assert_eq!(r.len(), 2);
        assert!(r[0].ai_generated && r[0].translated_at.is_some());
        assert!(!r[1].ai_generated && r[1].reviewed && r[1].reviewed_at.is_some());
        let c = csv(&r);
        assert!(c.starts_with("locale,key,origin,ai_generated,model"));
        assert!(c.contains("fr,a,machine,true,claude-haiku-5-5,"));
        assert!(c.contains("fr,\"b,c\",human,false,"));
        assert!(html(&r).contains("<td>claude-haiku-5-5</td>"));
        let cat = catalog(&r, "fr");
        assert_eq!(cat["a"]["origin"], "machine");
        assert_eq!(cat["a"]["score"], 91);
        assert_eq!(cat["b,c"]["reviewed"], true);
        assert_eq!(
            catalog_path("messages/{locale}.json", "fr"),
            "messages/fr.provenance.json"
        );
    }
}
