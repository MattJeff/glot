// Regenerates content/docs/cli.md from the binary's own help. Rerun at every release:
//   node scripts/gen-cli-docs.ts [path/to/glot]   (default: GLOT env, else ../target/integ/debug/glot, else `glot` on PATH)
import { execFileSync } from "node:child_process";
import { existsSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const local = path.resolve(root, "../target/integ/debug/glot");
const bin = process.argv[2] ?? process.env.GLOT ?? (existsSync(local) ? local : "glot");

const help = (args: string[]) => execFileSync(bin, [...args, "--help"], { encoding: "utf8" }).trimEnd();

/** Names listed under "Commands:" in a clap help text (minus `help`). */
function subcommands(text: string): string[] {
  const block = text.split(/^Commands:$/m)[1]?.split(/^\S/m)[0] ?? "";
  return [...block.matchAll(/^ {2}([a-z][\w-]*)/gm)].map((m) => m[1]).filter((c) => c !== "help");
}

const version = execFileSync(bin, ["--version"], { encoding: "utf8" }).trim();
const sections: string[] = [];
function walk(args: string[]) {
  const text = help(args);
  const about = text.split("\n")[0];
  sections.push(`## glot ${args.join(" ")}\n\n${about}\n\n\`\`\`text\n${text}\n\`\`\``);
  for (const c of subcommands(text)) walk([...args, c]);
}
const top = help([]);
for (const c of subcommands(top)) walk([c]);

const md = `# CLI reference

<!-- Generated by web/scripts/gen-cli-docs.ts from \`${version} --help\`. Do not edit by hand: rerun the script. -->

Generated from the help of \`${version}\`. Every command also prints this with \`glot <command> --help\`.

\`\`\`text
${top}
\`\`\`

${sections.join("\n\n")}
`;
writeFileSync(path.join(root, "content/docs/cli.md"), md);
console.log(`content/docs/cli.md: ${sections.length} commands from ${version}`);
